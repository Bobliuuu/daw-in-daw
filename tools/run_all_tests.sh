#!/bin/bash
# Runs every automated test: unit (plain Lua) + integration (inside REAPER). Writes docs/TEST_RESULTS.md.
# Requires: REAPER installed at /Applications/REAPER.app, system `lua` for the unit tests.
cd "$(dirname "$0")/.." || exit 1
ROOT="$PWD"; export DAW_OUT="$ROOT/out"; mkdir -p "$DAW_OUT"
rm -f "$DAW_OUT"/result_*.txt "$DAW_OUT"/DONE_*
SUMMARY=""; FAILED=0
run() { # name mode script [project]
  local name="$1" mode="$2" script="$3" proj="$4"
  echo ">>> $name"
  DAW_MODE="$mode" DAW_SELFTEST="${5:-}" TIMEOUT=300 tools/run_reaper.sh "$ROOT/$script" $proj >/dev/null
  local f="$DAW_OUT/result_$mode.txt"
  local line; line=$(grep -E '^== ' "$f" 2>/dev/null | tail -1)
  if [ -z "$line" ] && [ -f "$f" ]; then   # legacy prototype format: no summary line, count PASS/FAIL lines
    line="== $name: $(grep -c '^PASS' "$f") passed, $(grep -c '^FAIL' "$f") failed"
  fi
  [ -z "$line" ] && line="== $mode: NO RESULT (timeout/crash)" && FAILED=1
  grep -q "FAIL" "$f" 2>/dev/null && FAILED=1
  SUMMARY="$SUMMARY\n$line"; echo "$line"
}
echo ">>> unit tests (plain lua)"
UNIT=$(lua tests/unit.lua); echo "$UNIT"; echo "$UNIT" | grep -q " 0 failed" || FAILED=1
SUMMARY="$SUMMARY\n== unit: $(echo "$UNIT" | head -1)"
# original prototype (the five checks from the first go/no-go test)
run "legacy prototype build"  build  tests/legacy/daw_prototype.lua "" build
run "legacy prototype reopen" verify tests/legacy/daw_prototype.lua "$DAW_OUT/test_project.rpp" verify
run "engine build"   engine_build   tests/it_engine.lua
run "engine reopen"  engine_verify  tests/it_engine.lua "$DAW_OUT/engine.rpp"
rm -f "$DAW_OUT/neon_drive.rpp"
run "UI workflow (song build)"  ui_build   tests/it_ui_flow.lua
run "UI workflow (reopen+resume)" ui_verify  tests/it_ui_flow.lua "$DAW_OUT/neon_drive.rpp"
run "shipped example project" example tests/it_example.lua "$ROOT/examples/neon_drive.rpp"
run "robustness"     extra_robust   tests/it_extra.lua
run "window sizes"   extra_sizes    tests/it_extra.lua
run "performance"    extra_perf     tests/it_extra.lua
echo; echo "================ SUMMARY ================"; echo -e "$SUMMARY"
[ $FAILED -eq 0 ] && echo "ALL TESTS PASSED" || echo "SOME TESTS FAILED"
# ---- docs/TEST_RESULTS.md (generated)
{
  echo "# Test results"; echo
  echo "Generated by \`tools/run_all_tests.sh\` on $(date '+%Y-%m-%d %H:%M') with $(defaults read /Applications/REAPER.app/Contents/Info CFBundleShortVersionString) on $(sw_vers -productName) $(sw_vers -productVersion)."; echo
  echo "| Suite | Result |"; echo "|---|---|"
  echo -e "$SUMMARY" | grep '^==' | sed 's/^== \(.*\): \(.*\)$/| \1 | \2 |/'
  echo; echo "Overall: $([ $FAILED -eq 0 ] && echo PASS || echo FAIL)"; echo
  for m in build verify engine_build engine_verify ui_build ui_verify example extra_robust extra_sizes extra_perf; do
    echo "## $m"; echo '```'; cat "$DAW_OUT/result_$m.txt" 2>/dev/null; echo '```'; echo
  done
} > docs/TEST_RESULTS.md
exit $FAILED
